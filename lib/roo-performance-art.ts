type MeasuredCell = readonly [x: number, y: number, width: number, height: number, footCenterX: number, groundY: number, muzzleX: number, muzzleY: number, scale: number];
function measuredSheet(season: CinemaSeason, kind: PerformanceKind, width: number, height: number, bodyCenterX: number, cells: readonly MeasuredCell[], sourceRows: number = cells.length / 4): PerformanceSheet {
  return { src: `/images/ronny/welcome/performance/roo-${season}-${kind === "action" ? "balanced-action" : kind}.png`, width, height, columns: 4, rows: sourceRows, count: cells.length, optimizedWidth: 1920,
    scale: cells[0][8], bodyCenterX,
    registrations: cells.map(([x, y, width, height, footCenterX, groundY, muzzleX, muzzleY, scale]) => ({ crop: { x, y, width, height }, footCenterX, groundY, muzzle: [muzzleX, muzzleY], scale })),
  };
}

